#ifndef UTILS_HPP
#define UTILS_HPP

namespace RoselynEngine {
	struct Vector2f {
		float x = 0.0f;
		float y = 0.0f;
	};

	struct Vector3f {
		float x = 0.0f;
		float y = 0.0f;
		float z = 0.0f;
	};

	struct Vector2d {
		double x = 0.0;
		double y = 0.0;
	};

	struct Vector3d {
		double x = 0.0;
		double y = 0.0;
		double z = 0.0;
	};

	struct Vector2i {
		int x = 0;
		int y = 0;
	};

	struct Vector3i {
		int x = 0;
		int y = 0;
		int z = 0;
	};
}

#endif